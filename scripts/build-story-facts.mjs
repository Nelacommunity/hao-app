// Collects the facts Discover stories may be written from (culture, festivals, dishes, phrases, crafts and the
// relevant knowledge-base sections) into shared/stories/facts.generated.ts, which the generate-stories
// Edge Function bundles. Run with `npm run stories:facts` after changing src/data/* or the knowledge base.
import { register } from 'node:module';
import { writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);

// The data files use the app's path aliases (@shared/…, @/…) and extensionless imports.
register(
  'data:text/javascript,' +
    encodeURIComponent(`
const root = ${JSON.stringify(root.href)};
export async function resolve(specifier, context, next) {
  let s = specifier;
  if (s.startsWith('@shared/')) s = root + 'shared/' + s.slice(8);
  else if (s.startsWith('@/')) s = root + 'src/' + s.slice(2);
  if ((s.startsWith(root) || s.startsWith('.')) && !/\\.[a-z]+$/.test(s)) s += '.ts';
  return next(s, context);
}`)
);

const { CultureItems, Festivals } = await import(new URL('src/data/culture.ts', root).href);
const { Dishes } = await import(new URL('src/data/food.ts', root).href);
const { PhraseGroups } = await import(new URL('src/data/phrases.ts', root).href);
const { Crafts } = await import(new URL('src/data/crafts.ts', root).href);
const { SECTIONS } = await import(new URL('shared/ai/knowledge/data.generated.ts', root).href);

const ETIQUETTE = new Set(['chopsticks', 'ganbei', 'hot-water', 'bargaining', 'lucky-numbers', 'hongbao']);
const KNOWLEDGE = ['culture-etiquette-and-holidays', 'food-dietary-words-and-ordering-phrases', 'weather-and-climate-by-region'];

const facts = {
  culture: CultureItems.map(({ id, zh, pinyin, title, body, tip }) => ({ id, zh, pinyin, title, body, tip, etiquette: ETIQUETTE.has(id) })),
  festivals: Festivals.map(({ id, zh, name, body, tip }) => ({ id, zh, name, body, tip })),
  dishes: Dishes.map(({ id, name, nameZh, pinyin, region, spice, price, tags, description, orderZh, orderEn }) => ({
    id,
    name,
    nameZh,
    pinyin,
    region,
    spice,
    price,
    tags,
    description,
    orderZh,
    orderEn,
  })),
  phrases: PhraseGroups.flatMap((g) => g.phrases.map((p) => ({ group: g.id, groupTitle: g.title, ...p }))),
  crafts: Crafts,
  knowledge: KNOWLEDGE.map((id) => SECTIONS.find((s) => s.id === id)).filter(Boolean).map(({ id, title, body }) => ({ id, title, body })),
};

const out = `// GENERATED by scripts/build-story-facts.mjs from src/data and the knowledge base. Do not edit by hand.
import type { FactBundle } from './facts.ts';

export const FACTS: FactBundle = ${JSON.stringify(facts, null, 1)};
`;
writeFileSync(new URL('shared/stories/facts.generated.ts', root), out);
console.log(
  `Wrote ${facts.culture.length} culture items, ${facts.festivals.length} festivals, ${facts.dishes.length} dishes, ${facts.phrases.length} phrases, ${facts.crafts.length} crafts, ${facts.knowledge.length} knowledge sections.`
);
