// Inlines Leaflet (BSD-2-Clause) for the Android map, which runs in a WebView without loading anything
// from a CDN (CDNs are unreliable in mainland China). Run after upgrading leaflet: `npm run map:build`.
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const read = (p) => readFileSync(new URL(p, root), 'utf8');
const js = read('node_modules/leaflet/dist/leaflet.js').replace(/<\/script/gi, '<\\/script');
const css = read('node_modules/leaflet/dist/leaflet.css');
const { version } = JSON.parse(read('node_modules/leaflet/package.json'));

writeFileSync(
  new URL('src/components/map/leaflet-assets.generated.ts', root),
  `// GENERATED by scripts/build-map-assets.mjs from leaflet@${version} (BSD-2-Clause, © Volodymyr Agafonkin). Do not edit.\n` +
    `export const LEAFLET_JS = ${JSON.stringify(js)};\nexport const LEAFLET_CSS = ${JSON.stringify(css)};\n`
);
console.log(`Inlined leaflet@${version} (${Math.round((js.length + css.length) / 1024)} KB).`);
