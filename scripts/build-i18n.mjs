// Collects every string the app shows through t('…') / tx('…') / translate('…') into
// shared/i18n/catalog.generated.ts. The server only ever translates this list, so nobody can use the
// translation endpoint to translate their own text. Run `npm run i18n:build` after changing UI text.
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import ts from 'typescript';

const root = new URL('../', import.meta.url).pathname;
const FUNCS = new Set(['t', 'tx', 'translate']);

function* files(dir) {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) {
      if (name !== 'node_modules' && !path.endsWith(join('src', 'app', 'api'))) yield* files(path);
    } else if (/\.tsx?$/.test(name) && !name.endsWith('.generated.ts')) yield path;
  }
}

const strings = new Set();
const dynamic = [];
for (const dir of ['src', 'shared']) {
  for (const path of files(join(root, dir))) {
    const sf = ts.createSourceFile(path, readFileSync(path, 'utf8'), ts.ScriptTarget.Latest, true, path.endsWith('x') ? ts.ScriptKind.TSX : ts.ScriptKind.TS);
    const visit = (node) => {
      if (ts.isCallExpression(node) && ts.isIdentifier(node.expression) && FUNCS.has(node.expression.text) && node.arguments.length) {
        const arg = node.arguments[0];
        if (ts.isStringLiteral(arg) || ts.isNoSubstitutionTemplateLiteral(arg)) strings.add(arg.text);
        else if (ts.isTemplateExpression(arg)) dynamic.push(`${relative(root, path)}:${sf.getLineAndCharacterOfPosition(arg.getStart()).line + 1}`);
      }
      ts.forEachChild(node, visit);
    };
    visit(sf);
  }
}
if (dynamic.length) {
  console.error(`Template literals can't be translated; use t('… {name} …', { name }) instead:\n  ${dynamic.join('\n  ')}`);
  process.exit(1);
}

const catalog = [...strings].filter((s) => s.trim()).sort();
const hash = createHash('sha256').update(catalog.join('\u0000')).digest('hex').slice(0, 12);
const header = '// GENERATED by scripts/build-i18n.mjs. Do not edit by hand.\n';
writeFileSync(join(root, 'shared/i18n/catalog-hash.generated.ts'), `${header}export const CATALOG_HASH = '${hash}';\n`);
writeFileSync(
  join(root, 'shared/i18n/catalog.generated.ts'),
  `${header}export { CATALOG_HASH } from './catalog-hash.generated';\n\nexport const CATALOG: string[] = ${JSON.stringify(catalog, null, 1)};\n`
);
console.log(`${catalog.length} strings, ${catalog.reduce((n, s) => n + s.length, 0)} characters (catalog ${hash}).`);
