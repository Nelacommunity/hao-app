// Turns knowledge/*.md (exported from the team doc) into shared/ai/knowledge/data.generated.ts.
// Run with `npm run kb:build` after updating the Markdown files.
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const read = (path) => readFileSync(new URL(path, root), 'utf8').replace(/\r\n/g, '\n');

// ── Main guide: one retrieval section per `##` heading ──
const guide = read('knowledge/newcomer-setup.md');
const sections = [];
for (const block of guide.split(/^(?=## )/m).slice(1)) {
  const [heading, ...rest] = block.split('\n');
  const title = heading.replace(/^##\s+/, '').trim();
  const body = rest.join('\n').trim();
  if (body) sections.push({ id: title.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, ''), title, body });
}
const reviewed = guide.match(/^(\d{4}-\d{2}-\d{2})/m)?.[1] ?? '';

// ── Embassies: rows of the per-region tables ──
const embassies = [];
let region = '';
for (const line of read('knowledge/embassies.md').split('\n')) {
  const h = line.match(/^##\s+(.+)/);
  if (h) region = h[1].trim();
  const cells = line.split('|').slice(1, -1).map((c) => c.trim());
  if (region && cells.length === 3 && cells[0] !== 'Country' && !/^-+$/.test(cells[0])) {
    embassies.push({ country: cells[0], phone: cells[1], address: cells[2], region });
  }
}

if (sections.length < 10 || embassies.length < 100) {
  throw new Error(`Unexpected knowledge files: ${sections.length} sections, ${embassies.length} embassies`);
}

const out = `// GENERATED by scripts/build-knowledge.mjs from knowledge/*.md. Do not edit by hand.
import type { Embassy, KnowledgeSection } from './types';

export const KNOWLEDGE_REVIEWED = ${JSON.stringify(reviewed)};

export const SECTIONS: KnowledgeSection[] = ${JSON.stringify(sections, null, 1)};

export const EMBASSIES: Embassy[] = ${JSON.stringify(embassies)};
`;
writeFileSync(new URL('shared/ai/knowledge/data.generated.ts', root), out);
console.log(`Wrote ${sections.length} sections and ${embassies.length} embassies (reviewed ${reviewed || 'unknown'}).`);
