#!/usr/bin/env node
// Builds supabase/functions/places-chat/handler.js: the Places chat API route as `expo export` bundles it (one
// self-contained file, every dependency inside), wrapped as an ES module the Edge Function imports. See
// supabase/functions/places-chat/index.ts for why it runs there.
//
//   npm run build:places-function                 # expo export --platform web, then wrap the route
//   npm run build:places-function -- --no-export  # wrap the last export in dist/
import { execSync } from 'node:child_process';
import { existsSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const BUNDLE = join(ROOT, 'dist/server/_expo/functions/api/places-chat+api.js');
const OUT = join(ROOT, 'supabase/functions/places-chat/handler.js');

if (!process.argv.includes('--no-export')) {
  execSync('npx expo export --platform web', {
    cwd: ROOT,
    stdio: 'inherit',
    env: { ...process.env, NODE_OPTIONS: `${process.env.NODE_OPTIONS ?? ''} --max-old-space-size=6144`.trim() },
  });
}
if (!existsSync(BUNDLE)) {
  console.error(`Missing ${BUNDLE}: run without --no-export.`);
  process.exit(1);
}

let code = readFileSync(BUNDLE, 'utf8');

// Metro's prelude takes process from globalThis; the Edge Function hands it the env it mapped instead.
const PRELUDE = 'process=globalThis.process||{}';
if (!code.includes(PRELUDE)) throw new Error(`The bundle's prelude changed: "${PRELUDE}" not found in ${BUNDLE}`);
code = code.replace(PRELUDE, 'process={env:globalThis.__HAO_ENV||{}}');

const EXPORT = /\nmodule\.exports = (__r\(\d+\));\s*$/;
if (!EXPORT.test(code)) throw new Error(`The bundle no longer ends in module.exports = __r(…): ${BUNDLE}`);
code = code.replace(EXPORT, '\nconst __route = $1;\nexport default __route;\n');

// The public Mapbox token (shipped in the app too) for day plan routes, unless the container sets MAPBOX_TOKEN.
const mapbox = (readFileSync(join(ROOT, '.env'), 'utf8').match(/^EXPO_PUBLIC_MAPBOX_TOKEN=(.*)$/m)?.[1] ?? '').trim();
const header = [
  '// Generated by scripts/build-places-function.mjs from src/app/api/places-chat+api.ts. Do not edit.',
  'globalThis.__HAO_ENV ??= {};',
  `globalThis.__HAO_ENV.EXPO_PUBLIC_MAPBOX_TOKEN ??= ${JSON.stringify(mapbox)};`,
  '',
].join('\n');

writeFileSync(OUT, header + code);
console.log(`Wrote ${OUT} (${Math.round(statSync(OUT).size / 1024)} KB)`);
